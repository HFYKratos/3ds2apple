#!/usr/bin/env bash
# build-recomp-ios.sh — recompile one user ROM (or adopt existing generated C /
# archive) into arm64 iOS AOT code + build/game/<name>/code/librecomp.a.
#
# Per-game AOT pipeline (authoritative design: ios/zakuro-ios/scripts/AOT_BUILD.md §3/§9):
#
#   # once per Zakuro checkout (clone + patch + baseline lib):
#   scripts/build-zakuro-ios.sh
#
#   # per game (this script): 3dsrecomp port -> build/game/<name>/code/librecomp.a
#   scripts/build-recomp-ios.sh ROM/<your-game>.3ds <name>
#
#   # per game (linked libs):  libzakuro_ios.a + libgame.a in build/ios/<name>/
#   scripts/build-linked-ios-lib.sh <name>
#
#   # per game (AOT IPA):      IPA/<name>-AOT.ipa
#   scripts/build-game-ipa.sh <name>
#
# Must run on macOS with Xcode (iOS SDK clang) and Rust/cargo. The user's ROM
# is read from ROM/ (gitignored) and is never copied into the repository;
# generated C, objects and archives stay under build/ (gitignored).
#
# Version freezing (scripts/AOT_BUILD.md §5): the 3dsrecomp CLI is checked out at the
# revision that Zakuro's Cargo.lock pins for the `recomp-abi` crate, so the
# generated C uses the exact ABI the linked Zakuro accepts. If the Zakuro
# checkout is missing, a built-in fallback revision is used and a warning is
# printed; run scripts/build-zakuro-ios.sh first for the authoritative pin.
#
# Split/incremental path (2026-11-12 VM run): the generation step does not have
# to happen on the same machine/run as the iOS compile. All of these reuse
# existing state instead of regenerating hundreds of MB of C:
#
#   scripts/build-recomp-ios.sh pokemon-y --reuse
#       # build/game/pokemon-y/code/librecomp.a already exists: validate it,
#       # refresh recomp-info.txt (title ID from --title-id/src/main.rs).
#   scripts/build-recomp-ios.sh pokemon-y --archive /path/to/librecomp.a \
#       --title-id 0004000000055E00
#       # adopt an arm64 iOS archive compiled elsewhere (no ROM needed).
#   scripts/build-recomp-ios.sh pokemon-y --code-dir /path/from/linux/code \
#       --title-id 0004000000055E00
#       # adopt the C generated by 3dsrecomp elsewhere and compile it serially
#       # on the VM (incremental: up-to-date .o files are reused; --force redoes
#       # everything).
#
# 8 GB macOS VM: 3dsrecomp compiles the generated C in parallel by CPU count
# with no memory cap (scripts/AOT_BUILD.md §3.2). If `port` is killed by the OOM killer,
# re-run with --auto-serial (or --serial-compile) to finish compiling the
# already-generated C serially with the documented flags.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

AOT_LOG_PREFIX="build-recomp-ios"
# shellcheck source=lib/aot-common.sh
source "${SCRIPT_DIR}/lib/aot-common.sh"

# Built-in fallback: recomp-abi rev pinned by Zakuro's Cargo.lock at the time
# scripts/AOT_BUILD.md was written (§8.4: ABI 5 / generation 5). Prefer the Cargo.lock pin.
DEFAULT_RECOMP_REV="df82e6e3"

RECOMP_REPO_URL="https://github.com/fearkov/3dsrecomp"
IOS_TARGET="arm64-apple-ios16.0"

ROM_ARG=""
NAME_ARG=""
TITLE_ARG=""
RECOMP_DIR="${THREEDS_RECOMP_DIR:-${ROOT}/third_party/3dsrecomp}"
RECOMP_REV_ARG="${THREEDS_RECOMP_REV:-}"
RECOMP_BIN_ARG="${THREEDS_RECOMP_BIN:-}"
ZAKURO_DIR="${ZAKURO_DIR:-${ROOT}/third_party/zakuro}"
AUTO_SERIAL=0
SERIAL_COMPILE=0
KEEP_EXISTING=0
VERBOSE=0
REUSE=0
ARCHIVE_ARG=""
CODE_DIR_ARG=""
FORCE=0

EXPECTED_RECOMP_SYMBOLS="$AOT_EXPECTED_RECOMP_SYMBOLS"

NM_DUMP=""
cleanup_nm_dump() {
  [[ -z "${NM_DUMP:-}" ]] || rm -f -- "$NM_DUMP"
}
trap cleanup_nm_dump EXIT

usage() {
  cat <<'EOF'
Recompile one user ROM with 3dsrecomp into arm64 iOS AOT code.
Can also adopt already-generated C or an already-built archive (split builds).

Usage:
  scripts/build-recomp-ios.sh <rom> [name] [options]
  scripts/build-recomp-ios.sh <name> --reuse [options]
  scripts/build-recomp-ios.sh <name> --archive <librecomp.a> [options]
  scripts/build-recomp-ios.sh <name> --code-dir <dir> [options]

Arguments:
  <rom>              Decrypted .3ds/.cci ROM path (relative to the repo root;
                     the ROM itself is gitignored and never copied into git).
                     Not needed for --reuse/--archive/--code-dir adoption.
  [name]             Short game name for build/game/<name>/ (default: derived
                     from the ROM file name, e.g. "Pokemon Y.cci" -> pokemon-y)

Options:
  --name NAME        Same as the [name] argument
  --title-id ID      16 hex digit title ID; normally extracted from the
                     generated src/main.rs (scripts/AOT_BUILD.md §3.2). Explicit value wins
                     and is validated/normalised (lower case and 0x are OK).
  --reuse            Do not generate anything: validate the existing
                     build/game/<name>/code/librecomp.a, refresh
                     recomp-info.txt, and stop. No ROM needed.
  --archive PATH     Adopt an existing arm64 iOS librecomp.a built elsewhere
                     (e.g. copied from the real VM run), copy it into
                     build/game/<name>/code/librecomp.a, validate, write
                     recomp-info.txt and stop. No ROM/3dsrecomp needed.
  --code-dir DIR     Adopt the C/H files generated by 3dsrecomp elsewhere
                     (e.g. on Linux) and compile them here serially. Implies
                     --serial-compile; incremental by default (see --force).
  --force            With --serial-compile/--code-dir: recompile every .c file
                     even if the .o is newer (default: incremental reuse).
  --recomp-rev REV   3dsrecomp revision; default: Zakuro Cargo.lock's
                     recomp-abi pin (env: THREEDS_RECOMP_REV)
  --recomp-dir DIR   3dsrecomp checkout (default: third_party/3dsrecomp;
                     env: THREEDS_RECOMP_DIR)
  --recomp-bin PATH  Reuse an already-built 3dsrecomp binary; skips
                     clone/build (env: THREEDS_RECOMP_BIN)
  --auto-serial      If `port` fails, retry compiling the generated C serially
                     (use on the 8 GB macOS VM; scripts/AOT_BUILD.md §3.2)
  --serial-compile   Skip `port` and only compile the existing generated C in
                     build/game/<name>/code/ serially (recovery path)
  --keep-existing    Do not delete an existing build/game/<name>/ first
  --verbose          Stream 3dsrecomp/cargo output to the terminal as well
  -h, --help         Show this help and exit

Outputs (all gitignored):
  build/game/<name>/code/librecomp.a    arm64 iOS archive of the recompiled C
  build/game/<name>/src/main.rs         desktop project written by `port`
                                        (only its title ID is used on iOS)
  build/game/<name>/recomp-info.txt     rev / title ID / archive SHA256 summary
  build/logs/build-recomp-ios-<name>-*.log

Exit status: 0 on success, non-zero on failure (the log tail is printed).
EOF
}

log() {
  printf '[build-recomp-ios] %s\n' "$*"
}

warn() {
  printf '[build-recomp-ios] warning: %s\n' "$*" >&2
}

die() {
  printf 'error: %s\n' "$*" >&2
  exit 1
}

resolve_path() {
  case "$1" in
    /*) printf '%s\n' "$1" ;;
    *) printf '%s\n' "${ROOT}/$1" ;;
  esac
}

need_tool() {
  command -v "$1" >/dev/null 2>&1 || die "'$1' not found in PATH. $2"
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --name)
      [[ $# -ge 2 ]] || die "--name requires a value"
      NAME_ARG="$2"
      shift 2
      ;;
    --title-id)
      [[ $# -ge 2 ]] || die "--title-id requires a value"
      TITLE_ARG="$2"
      shift 2
      ;;
    --reuse)
      REUSE=1
      shift
      ;;
    --archive)
      [[ $# -ge 2 ]] || die "--archive requires a value"
      ARCHIVE_ARG="$2"
      REUSE=1
      shift 2
      ;;
    --code-dir)
      [[ $# -ge 2 ]] || die "--code-dir requires a value"
      CODE_DIR_ARG="$2"
      SERIAL_COMPILE=1
      shift 2
      ;;
    --force)
      FORCE=1
      shift
      ;;
    --recomp-rev)
      [[ $# -ge 2 ]] || die "--recomp-rev requires a value"
      RECOMP_REV_ARG="$2"
      shift 2
      ;;
    --recomp-dir)
      [[ $# -ge 2 ]] || die "--recomp-dir requires a value"
      RECOMP_DIR="$2"
      shift 2
      ;;
    --recomp-bin)
      [[ $# -ge 2 ]] || die "--recomp-bin requires a value"
      RECOMP_BIN_ARG="$2"
      shift 2
      ;;
    --auto-serial)
      AUTO_SERIAL=1
      shift
      ;;
    --serial-compile)
      SERIAL_COMPILE=1
      shift
      ;;
    --keep-existing)
      KEEP_EXISTING=1
      shift
      ;;
    --verbose)
      VERBOSE=1
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    -*)
      die "unknown option: $1 (try --help)"
      ;;
    *)
      if [[ -z "$ROM_ARG" ]]; then
        ROM_ARG="$1"
      elif [[ -z "$NAME_ARG" ]]; then
        NAME_ARG="$1"
      else
        die "unexpected argument: $1 (try --help)"
      fi
      shift
      ;;
  esac
done

# A ROM is required unless we adopt existing build state. In adoption mode the
# first positional may be the game name instead of a ROM path.
if [[ -n "$ROM_ARG" ]]; then
  if [[ -f "$(resolve_path "$ROM_ARG")" ]]; then
    :
  elif [[ "$REUSE" -eq 1 || "$SERIAL_COMPILE" -eq 1 ]]; then
    if [[ -n "$NAME_ARG" ]]; then
      die "ROM not found: $(resolve_path "$ROM_ARG")
       (--reuse/--archive/--code-dir do not need a ROM; pass just <name>)"
    fi
    NAME_ARG="$ROM_ARG"
    ROM_ARG=""
  else
    die "ROM not found: $(resolve_path "$ROM_ARG")
       (the ROM is gitignored; keep it under ROM/)"
  fi
fi
if [[ -z "$ROM_ARG" && "$REUSE" -ne 1 && "$SERIAL_COMPILE" -ne 1 ]]; then
  die "missing <rom> argument
usage: scripts/build-recomp-ios.sh <rom> [name] [options]"
fi

# Adoption modes are mutually exclusive; silently letting one win hides a
# mistake in a long build command.
if [[ -n "$ARCHIVE_ARG" && -n "$CODE_DIR_ARG" ]]; then
  die "--archive and --code-dir cannot be combined (choose one adoption mode)"
fi
if [[ -n "$ARCHIVE_ARG" && "$SERIAL_COMPILE" -eq 1 && -z "$CODE_DIR_ARG" ]]; then
  die "--archive cannot be combined with --serial-compile (an archive is already built)"
fi

# --- host / tool checks ------------------------------------------------------
if [[ "$(uname -s)" != "Darwin" ]]; then
  die "this script must run on macOS with Xcode (iOS SDK clang) installed.
       Detected $(uname -s); run it on the macOS VM.
       (On Linux only scripts/tests/aot-selfcheck.sh and the simulated harness
       scripts/tests/aot-sim-harness.sh can run; they use fake toolchains in a
       temp dir, see AOT_BUILD.md §11.)"
fi

need_tool xcrun "Install Xcode and run: sudo xcode-select -s \"\$HOME/Applications/Xcode-16.4.0.app\""
need_tool ar "Install the Xcode command line tools: xcode-select --install"
need_tool nm "Install the Xcode command line tools: xcode-select --install"
# Adoption modes (--reuse/--archive/--code-dir/--serial-compile) never invoke
# cargo/git: do not force a Rust toolchain on a VM that only compiles/relinks.
if [[ "$REUSE" -ne 1 && "$SERIAL_COMPILE" -ne 1 ]]; then
  need_tool git "Install the Xcode command line tools: xcode-select --install"
  need_tool cargo "Install Rust (https://rustup.rs) and the aarch64-apple-ios target"
fi

SDK_PATH="$(xcrun --sdk iphoneos --show-sdk-path 2>/dev/null)" \
  || die "cannot locate the iOS SDK (xcrun --sdk iphoneos --show-sdk-path failed).
       Install the iOS platform in Xcode 16.4, then retry."
CC_BIN="$(xcrun --sdk iphoneos -f clang 2>/dev/null)" \
  || die "cannot locate the iOS SDK clang (xcrun --sdk iphoneos -f clang failed)."
case "$SDK_PATH" in
  *" "*)
    die "the iOS SDK path contains spaces, which 3dsrecomp's CC handling cannot
       represent: '$SDK_PATH'. Move Xcode to a path without spaces."
    ;;
esac
[[ -n "$SDK_PATH" && -d "$SDK_PATH" ]] || die "iOS SDK path is not a directory: $SDK_PATH"
[[ -n "$CC_BIN" && -x "$CC_BIN" ]] || die "iOS SDK clang is not executable: $CC_BIN"

# --- resolve ROM and name ----------------------------------------------------
if [[ -n "$ROM_ARG" ]]; then
  ROM_ABS="$(resolve_path "$ROM_ARG")"
  [[ -r "$ROM_ABS" ]] || die "ROM is not readable: $ROM_ABS"
  ROM_BYTES="$(wc -c < "$ROM_ABS" | tr -d '[:space:]')"
  [[ "$ROM_BYTES" -gt 0 ]] || die "ROM is empty: $ROM_ABS"
  case "$ROM_ABS" in
    *.cia)
      warn "input ends in .cia: 3dsrecomp rejects update CIAs and iOS FFI does not
       load update/DLC yet (scripts/AOT_BUILD.md §6). Use the base-game .3ds/.cci ROM."
      ;;
  esac
  if [[ -z "$NAME_ARG" ]]; then
    NAME_ARG="$(printf '%s\n' "$(basename "$ROM_ABS")" \
      | sed -e 's/\.3ds$//' -e 's/\.cci$//' -e 's/\.cia$//' \
      | tr '[:upper:]' '[:lower:]' \
      | tr -cs 'a-z0-9._-' '-' \
      | sed -e 's/^-*//' -e 's/-*$//')"
  fi
else
  ROM_ABS=""
  ROM_BYTES=""
fi
NAME="$NAME_ARG"
[[ -n "$NAME" ]] || die "could not derive a game name; pass one explicitly"
aot_is_valid_name "$NAME" \
  || die "invalid game name: '$NAME' (use letters, digits, '.', '_', '-')"

OUT_DIR="${ROOT}/build/game/${NAME}"
CODE_DIR="${OUT_DIR}/code"
ARCHIVE="${CODE_DIR}/librecomp.a"
INFO_FILE="${OUT_DIR}/recomp-info.txt"
LOG_DIR="${ROOT}/build/logs"
mkdir -p "$LOG_DIR"
LOG_FILE="${LOG_DIR}/build-recomp-ios-${NAME}-$(date +%Y%m%d-%H%M%S).log"
: > "$LOG_FILE"

if [[ -n "$ROM_ABS" ]]; then
  log "repo root:  $ROOT"
  log "rom:        $ROM_ABS (${ROM_BYTES} bytes)"
else
  log "repo root:  $ROOT"
  log "rom:        (none: adopting existing build state)"
fi
log "game name:  $NAME"
log "output:     $OUT_DIR"
log "ios target: $IOS_TARGET"
log "ios sdk:    $SDK_PATH"
log "build log:  $LOG_FILE"

# --- title ID helpers --------------------------------------------------------
# Resolution order for adopted state: --title-id, existing recomp-info.txt,
# generated src/main.rs, then build/ios/<name>/build-info.txt (what the linked
# library was built for). Always validated; corrupted values are repaired with
# a warning by aot_normalize_title_id.
# Preference: when a freshly generated/adopted src/main.rs exists it is newer
# than an old recomp-info.txt; for --reuse (C gone) the existing recomp-info is
# the only source. PREFER_RUST selects the order.
PREFER_RUST=1
resolve_title_id_for_adoption() {
  local cand norm
  if [[ -n "$TITLE_ARG" ]]; then
    if norm="$(aot_normalize_title_id "$TITLE_ARG")"; then
      TITLE_ID="$norm"
      TITLE_ID_SOURCE="--title-id"
      return 0
    fi
    aot_warn "--title-id is not a valid 16 hex digit title ID: '$TITLE_ARG'"
    return 1
  fi
  if [[ "$PREFER_RUST" -eq 1 ]]; then
    if norm="$(aot_title_id_from_rust "${OUT_DIR}/src/main.rs" || true)"; then
      TITLE_ID="$norm"
      TITLE_ID_SOURCE="src/main.rs"
      return 0
    fi
  fi
  cand="$(aot_info_value "$INFO_FILE" title_id || true)"
  if [[ -n "$cand" ]]; then
    if norm="$(aot_normalize_title_id "$cand")"; then
      TITLE_ID="$norm"
      TITLE_ID_SOURCE="recomp-info.txt"
      return 0
    fi
    aot_warn "invalid title_id='$cand' in $INFO_FILE (ignored)"
  fi
  if [[ "$PREFER_RUST" -eq 0 ]]; then
    if norm="$(aot_title_id_from_rust "${OUT_DIR}/src/main.rs" || true)"; then
      TITLE_ID="$norm"
      TITLE_ID_SOURCE="src/main.rs"
      return 0
    fi
  fi
  cand="$(aot_info_value "${ROOT}/build/ios/${NAME}/build-info.txt" title_id || true)"
  if [[ -n "$cand" ]]; then
    if norm="$(aot_normalize_title_id "$cand")"; then
      TITLE_ID="$norm"
      TITLE_ID_SOURCE="build/ios/${NAME}/build-info.txt"
      return 0
    fi
  fi
  return 1
}

# --- archive validation (scripts/AOT_BUILD.md §3.2/§8.2) --------------------------------
validate_archive() {
  local archive="$1" missing="" symbol
  [[ -f "$archive" ]] || die "generated archive is missing: $archive"
  [[ -s "$archive" ]] || die "generated archive is empty: $archive"

  aot_lipo_arch_ok "$archive" \
    || die "archive is not an arm64 iOS archive (expected arm64):
       $AOT_LIPO_INFO
       Check CC='$(xcrun --sdk iphoneos -f clang) -target $IOS_TARGET -isysroot <sdk>'."

  # One nm dump + exact last-field matching (no `nm | grep -q`: under
  # `set -o pipefail` an early grep exit gives nm SIGPIPE and a present table
  # symbol looks missing).
  NM_DUMP="$(mktemp "${TMPDIR:-/tmp}/3ds2apple-nm.XXXXXX")"
  aot_nm_dump "$archive" "$NM_DUMP" -g \
    || die "nm -g failed on $archive"
  for symbol in $EXPECTED_RECOMP_SYMBOLS; do
    aot_nm_has_symbol "$NM_DUMP" "_${symbol}" || missing="$missing _${symbol}"
  done
  rm -f -- "$NM_DUMP"
  NM_DUMP=""
  [[ -z "$missing" ]] || die "archive is missing 3dsrecomp table symbols:$missing
       The C was probably not compiled by 3dsrecomp's port step. See scripts/AOT_BUILD.md §3.2."
}

COMPILE_MODE="port"
ADOPTED_FROM=""

# --- adoption: already-built archive (--archive / --reuse) -------------------
write_recomp_info() {
  local sha bytes
  aot_validate_title_id "$TITLE_ID" \
    || die "refusing to write recomp-info.txt: title ID '$TITLE_ID' is not 16 hex digits.
       Pass --title-id explicitly (see AOT_BUILD.md §2)."
  sha="$(aot_sha256 "$ARCHIVE")"
  bytes="$(wc -c < "$ARCHIVE" | tr -d '[:space:]')"
  {
    printf 'name=%s\n' "$NAME"
    printf 'title_id=%s\n' "$TITLE_ID"
    printf 'title_id_source=%s\n' "${TITLE_ID_SOURCE:-unknown}"
    printf 'recomp_rev=%s\n' "${RECOMP_REV_USED:-unknown}"
    printf 'recomp_dir=%s\n' "${RECOMP_SOURCE:-unknown}"
    printf 'compile_mode=%s\n' "$COMPILE_MODE"
    printf 'ios_target=%s\n' "$IOS_TARGET"
    printf 'sdk=%s\n' "$SDK_PATH"
    printf 'archive=%s\n' "$ARCHIVE"
    printf 'archive_bytes=%s\n' "$bytes"
    printf 'archive_sha256=%s\n' "$sha"
    if [[ -n "$ADOPTED_FROM" ]]; then
      printf 'adopted_from=%s\n' "$ADOPTED_FROM"
    fi
    printf 'rom_basename=%s\n' "${ROM_BASENAME:-unknown}"
    printf 'rom_bytes=%s\n' "${ROM_BYTES:-unknown}"
    printf 'rom_sha256=%s\n' "$ROM_SHA"
    printf 'created_utc=%s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  } > "$INFO_FILE"
  log "recompiled code ready"
  log "  archive:  $ARCHIVE ($bytes bytes)"
  log "  sha256:   $sha"
  log "  title id: $TITLE_ID (source: ${TITLE_ID_SOURCE:-unknown})"
  log "  mode:     $COMPILE_MODE"
  log "  info:     $INFO_FILE"
  log "next: scripts/build-linked-ios-lib.sh ${NAME}"
}

if [[ "$REUSE" -eq 1 ]]; then
  ROM_BASENAME=""
  ROM_SHA=""
  if [[ -n "$ROM_ABS" ]]; then
    ROM_BASENAME="$(basename "$ROM_ABS")"
    ROM_SHA="$(aot_sha256 "$ROM_ABS")"
  fi
  # Preserve ROM metadata from an earlier run when no ROM is passed now.
  [[ -n "$ROM_BASENAME" ]] || ROM_BASENAME="$(aot_info_value "$INFO_FILE" rom_basename || true)"
  [[ -n "$ROM_SHA" ]] || ROM_SHA="$(aot_info_value "$INFO_FILE" rom_sha256 || true)"
  [[ -n "$ROM_BYTES" ]] || ROM_BYTES="$(aot_info_value "$INFO_FILE" rom_bytes || true)"
  [[ -n "${ROM_BASENAME:-}" ]] || ROM_BASENAME="unknown"
  [[ -n "${ROM_SHA:-}" ]] || ROM_SHA="unknown"
  [[ -n "${ROM_BYTES:-}" ]] || ROM_BYTES="unknown"

  if [[ -n "$ARCHIVE_ARG" ]]; then
    PREFER_RUST=1
    ARCHIVE_SRC="$(resolve_path "$ARCHIVE_ARG")"
    [[ -f "$ARCHIVE_SRC" ]] || die "--archive file not found: $ARCHIVE_SRC"
    log "adopting existing archive: $ARCHIVE_SRC"
    validate_archive "$ARCHIVE_SRC"
    mkdir -p "$CODE_DIR"
    if [[ "$(cd "$(dirname "$ARCHIVE_SRC")" && pwd)/$(basename "$ARCHIVE_SRC")" \
          != "$(cd "$CODE_DIR" && pwd)/$(basename "$ARCHIVE")" ]]; then
      cp -f "$ARCHIVE_SRC" "$ARCHIVE"
      ADOPTED_FROM="$ARCHIVE_SRC"
    fi
    # A sibling src/main.rs (same 3dsrecomp output tree) supplies the title ID.
    for sibling in "$(dirname "$ARCHIVE_SRC")/../src/main.rs" "$(dirname "$ARCHIVE_SRC")/src/main.rs"; do
      if [[ -f "$sibling" && ! -f "${OUT_DIR}/src/main.rs" ]]; then
        mkdir -p "${OUT_DIR}/src"
        cp -f "$sibling" "${OUT_DIR}/src/main.rs"
        log "copied title source: $sibling -> ${OUT_DIR}/src/main.rs"
        break
      fi
    done
    COMPILE_MODE="adopted-archive"
  else
    [[ -f "$ARCHIVE" ]] || die "--reuse needs an existing archive: $ARCHIVE
       (run once without --reuse, or pass --archive <librecomp.a>)"
    log "reusing existing archive: $ARCHIVE"
    PREFER_RUST=0
    validate_archive "$ARCHIVE"
    COMPILE_MODE="reuse"
  fi
  validate_archive "$ARCHIVE"
  resolve_title_id_for_adoption \
    || die "could not determine a valid 16 hex digit title ID for '$NAME'.
       Pass --title-id 0004000000055E00 (or the ROM's real title ID) so
       recomp-info.txt and the manifest are correct."
  RECOMP_REV_USED="$(aot_info_value "$INFO_FILE" recomp_rev || true)"
  [[ -n "$RECOMP_REV_USED" ]] || RECOMP_REV_USED="adopted"
  RECOMP_SOURCE="$(aot_info_value "$INFO_FILE" recomp_dir || true)"
  [[ -n "$RECOMP_SOURCE" ]] || RECOMP_SOURCE="adopted"
  write_recomp_info
  printf '%s\n' "$ARCHIVE"
  exit 0
fi

# --- serial compile fallback (scripts/AOT_BUILD.md §3.2, incremental) ------------------
serial_compile() {
  local c_files c_file obj base index=0 total compiled=0 skipped=0
  local -a obj_names
  obj_names=()
  shopt -s nullglob
  c_files=("${CODE_DIR}"/*.c)
  local o_files
  o_files=("${CODE_DIR}"/*.o)
  shopt -u nullglob
  if [[ "${#c_files[@]}" -eq 0 ]]; then
    if [[ "${#o_files[@]}" -gt 0 ]]; then
      log "serial compile: no C files in ${CODE_DIR}; reusing the ${#o_files[@]} existing object(s)"
      if ! ( cd "$CODE_DIR" && rm -f librecomp.a && ar rcs librecomp.a ./*.o ) >>"$LOG_FILE" 2>&1; then
        die "ar failed while creating $ARCHIVE from existing objects; full log: $LOG_FILE"
      fi
      COMPILE_MODE="objects-only"
      return 0
    fi
    die "no generated C files in ${CODE_DIR}.
       Use --code-dir <dir> to adopt C generated elsewhere, or run without
       --serial-compile first (--serial-compile only recompiles existing C)."
  fi
  total="${#c_files[@]}"

  log "serial compile: ${total} C files with $(basename "$CC_BIN") (incremental unless --force)"
  for c_file in "${c_files[@]}"; do
    base="$(basename "$c_file")"
    obj="${base%.c}.o"
    # Archive exactly one object per current C file (in C-file order). Archiving
    # a wildcard would also pick up stale .o files for C files that no longer
    # exist, which can surface as duplicate/incorrect symbols at the app link.
    obj_names[${#obj_names[@]}]="$obj"
    index=$((index + 1))
    if [[ "$FORCE" -eq 0 && -f "${CODE_DIR}/${obj}" && "${CODE_DIR}/${obj}" -nt "$c_file" ]]; then
      skipped=$((skipped + 1))
      continue
    fi
    if (( index % 20 == 0 || index == total )); then
      log "  serial compile: ${index}/${total} (${base})"
    fi
    if ! ( cd "$CODE_DIR" && "$CC_BIN" \
        -target "$IOS_TARGET" -isysroot "$SDK_PATH" \
        -O2 -ffp-contract=off -fno-math-errno -w \
        -fPIC -fvisibility=hidden -I. \
        -c "$base" -o "$obj" ) >>"$LOG_FILE" 2>&1; then
      printf '\n--- serial compile failed: last 40 lines of %s ---\n' "$LOG_FILE" >&2
      tail -n 40 "$LOG_FILE" >&2
      die "serial compile failed for $base; full log: $LOG_FILE"
    fi
    compiled=$((compiled + 1))
  done

  log "serial compile: compiled ${compiled}, reused ${skipped} up-to-date object(s)"
  log "serial compile: archiving ${#obj_names[@]} objects -> $(basename "$ARCHIVE")"
  if ! ( cd "$CODE_DIR" && rm -f librecomp.a && ar rcs librecomp.a "${obj_names[@]}" ) >>"$LOG_FILE" 2>&1; then
    printf '\n--- ar failed: last 40 lines of %s ---\n' "$LOG_FILE" >&2
    tail -n 40 "$LOG_FILE" >&2
    die "ar failed while creating $ARCHIVE"
  fi
  if [[ "$compiled" -eq 0 && "$skipped" -gt 0 ]]; then
    COMPILE_MODE="serial-incremental"
  else
    COMPILE_MODE="serial"
  fi
}

# --- adopt generated C from another directory (--code-dir) ------------------
if [[ -n "$CODE_DIR_ARG" ]]; then
  CODE_SRC="$(resolve_path "$CODE_DIR_ARG")"
  [[ -d "$CODE_SRC" ]] || die "--code-dir is not a directory: $CODE_SRC"
  mkdir -p "$CODE_DIR"
  copied=0
  shopt -s nullglob
  for f in "$CODE_SRC"/*.c "$CODE_SRC"/*.h; do
    target="${CODE_DIR}/$(basename "$f")"
    # Copy when the file is missing or newer than the adopted copy, so a re-run
    # picks up C regenerated upstream while unchanged files keep their .o cache
    # valid (serial_compile skips objects newer than their C). --force always
    # refreshes AND recompiles.
    if [[ "$FORCE" -eq 1 || ! -e "$target" || "$f" -nt "$target" ]]; then
      cp -f "$f" "$target"
      copied=$((copied + 1))
    fi
  done
  shopt -u nullglob
  log "adopted generated C from $CODE_SRC (${copied} new/updated file(s) copied to $CODE_DIR)"
  ADOPTED_FROM="$CODE_SRC"
  # src/main.rs written by 3dsrecomp one directory up supplies the title ID.
  if [[ -f "${CODE_SRC}/../src/main.rs" && ! -f "${OUT_DIR}/src/main.rs" ]]; then
    mkdir -p "${OUT_DIR}/src"
    cp -f "${CODE_SRC}/../src/main.rs" "${OUT_DIR}/src/main.rs"
    log "copied title source: ${CODE_SRC}/../src/main.rs -> ${OUT_DIR}/src/main.rs"
  fi
  ROM_BASENAME="$(aot_info_value "$INFO_FILE" rom_basename || true)"
  ROM_SHA="$(aot_info_value "$INFO_FILE" rom_sha256 || true)"
  [[ -n "$ROM_BASENAME" ]] || ROM_BASENAME="unknown"
  [[ -n "$ROM_SHA" ]] || ROM_SHA="unknown"
  [[ -n "$ROM_BYTES" ]] || ROM_BYTES="unknown"
  serial_compile
  validate_archive "$ARCHIVE"
  if ! resolve_title_id_for_adoption; then
    TITLE_ID=""
    die "could not determine a valid 16 hex digit title ID for '$NAME'.
       Pass --title-id 0004000000055E00 (the generated src/main.rs was not
       found next to the adopted C)."
  fi
  RECOMP_REV_USED="$(aot_info_value "$INFO_FILE" recomp_rev || true)"
  [[ -n "$RECOMP_REV_USED" ]] || RECOMP_REV_USED="adopted"
  RECOMP_SOURCE="$(aot_info_value "$INFO_FILE" recomp_dir || true)"
  [[ -n "$RECOMP_SOURCE" ]] || RECOMP_SOURCE="adopted"
  write_recomp_info
  printf '%s\n' "$ARCHIVE"
  exit 0
fi

# --- run_stage helper --------------------------------------------------------
run_stage() {
  local label="$1"
  shift
  if [[ "$VERBOSE" -eq 1 ]]; then
    if ! "$@" 2>&1 | tee -a "$LOG_FILE"; then
      die "$label failed; full log: $LOG_FILE"
    fi
  elif ! "$@" >>"$LOG_FILE" 2>&1; then
    printf '\n--- %s failed: last 80 lines of %s ---\n' "$label" "$LOG_FILE" >&2
    tail -n 80 "$LOG_FILE" >&2
    die "$label failed; full log: $LOG_FILE"
  fi
}

# --- resolve the 3dsrecomp revision (scripts/AOT_BUILD.md §5) ---------------------------
resolve_recomp_rev() {
  if [[ -n "$RECOMP_REV_ARG" ]]; then
    printf '%s\n' "$RECOMP_REV_ARG"
    return 0
  fi

  local lock="${ZAKURO_DIR}/Cargo.lock"
  if [[ -f "$lock" ]]; then
    local source_line rev
    source_line="$(grep -A4 '^name = "recomp-abi"$' "$lock" 2>/dev/null \
      | grep 'fearkov/3dsrecomp' | sed -n '1p' || true)"
    if [[ -n "$source_line" ]]; then
      rev="$(printf '%s\n' "$source_line" | sed -nE 's/.*#([0-9a-fA-F]{7,40})".*/\1/p' | sed -n '1p')"
      if [[ -n "$rev" ]]; then
        printf '%s\n' "$rev"
        return 0
      fi
    fi
  fi

  warn "Zakuro Cargo.lock pin not found (${lock}); using built-in fallback
       revision ${DEFAULT_RECOMP_REV}. Run scripts/build-zakuro-ios.sh first
       so the recomp-abi pin is authoritative (scripts/AOT_BUILD.md §5)."
  printf '%s\n' "$DEFAULT_RECOMP_REV"
}

# --- build / reuse the 3dsrecomp CLI ----------------------------------------
# --serial-compile only recompiles C that is already on disk with the iOS SDK
# clang, so it must not clone/build 3dsrecomp (no cargo/git needed on the VM).
if [[ "$SERIAL_COMPILE" -eq 1 ]]; then
  RECOMP_REV_USED="$(aot_info_value "$INFO_FILE" recomp_rev || true)"
  [[ -n "$RECOMP_REV_USED" ]] || RECOMP_REV_USED="serial-compile"
  RECOMP_SOURCE="$(aot_info_value "$INFO_FILE" recomp_dir || true)"
  [[ -n "$RECOMP_SOURCE" ]] || RECOMP_SOURCE="serial-compile"
  log "serial-compile mode: 3dsrecomp CLI is not needed, skipping its build"
else
  RECOMP_REV_USED="prebuilt"
  RECOMP_SOURCE="prebuilt (--recomp-bin)"

  build_recomp_cli() {
    ( cd "$RECOMP_DIR" && cargo build --release )
  }

  if [[ -n "$RECOMP_BIN_ARG" ]]; then
    RECOMP_BIN="$(resolve_path "$RECOMP_BIN_ARG")"
    [[ -x "$RECOMP_BIN" ]] || die "--recomp-bin is not executable: $RECOMP_BIN"
    log "using prebuilt 3dsrecomp: $RECOMP_BIN"
  else
    RECOMP_DIR="$(resolve_path "$RECOMP_DIR")"
    RECOMP_SOURCE="$RECOMP_DIR"
    RECOMP_REV_USED="$(resolve_recomp_rev)"
    case "$RECOMP_REV_USED" in
      *[!0-9a-fA-F]*) die "invalid 3dsrecomp revision: '$RECOMP_REV_USED' (expected a git rev)" ;;
    esac
    log "3dsrecomp: $RECOMP_DIR"
    log "3dsrecomp rev: $RECOMP_REV_USED"

    if [[ ! -d "$RECOMP_DIR/.git" ]]; then
      if [[ -e "$RECOMP_DIR" ]]; then
        die "$RECOMP_DIR exists but is not a git checkout.
       Remove it (it is gitignored build state) or pass --recomp-dir/--recomp-bin."
      fi
      mkdir -p "$(dirname "$RECOMP_DIR")"
      log "cloning $RECOMP_REPO_URL (one-time) ..."
      git clone "$RECOMP_REPO_URL" "$RECOMP_DIR"
    fi

    if ! git -C "$RECOMP_DIR" rev-parse --verify -q "${RECOMP_REV_USED}^{commit}" >/dev/null 2>&1; then
      log "fetching 3dsrecomp rev $RECOMP_REV_USED ..."
      git -C "$RECOMP_DIR" fetch --tags --quiet origin || warn "git fetch --tags failed"
      git -C "$RECOMP_DIR" fetch --quiet origin "$RECOMP_REV_USED" 2>/dev/null \
        || warn "git fetch origin $RECOMP_REV_USED failed (will rely on existing objects)"
    fi
    git -C "$RECOMP_DIR" rev-parse --verify -q "${RECOMP_REV_USED}^{commit}" >/dev/null 2>&1 \
      || die "3dsrecomp revision '$RECOMP_REV_USED' is not available in $RECOMP_DIR.
       Check network access or pass --recomp-rev <rev>."
    log "checking out 3dsrecomp @ $RECOMP_REV_USED ..."
    git -C "$RECOMP_DIR" checkout --quiet --detach "$RECOMP_REV_USED"

    log "building the 3dsrecomp CLI (cargo build --release) ..."
    run_stage "cargo build (3dsrecomp)" build_recomp_cli
    RECOMP_BIN="${RECOMP_DIR}/target/release/3dsrecomp"
    [[ -x "$RECOMP_BIN" ]] || die "3dsrecomp CLI was not produced at $RECOMP_BIN"
  fi
fi

# --- run port with the iOS clang (scripts/AOT_BUILD.md §3.2) ----------------------------
CC_STRING="${CC_BIN} -target ${IOS_TARGET} -isysroot ${SDK_PATH}"
log "CC: ${CC_STRING}"
log "AR: ar"

if [[ "$SERIAL_COMPILE" -eq 1 ]]; then
  [[ -d "$CODE_DIR" ]] || die "--serial-compile needs generated C in $CODE_DIR.
       Run this script once without --serial-compile first, or adopt the tree
       with --code-dir <dir>."
  serial_compile
else
  if [[ -d "$OUT_DIR" && "$KEEP_EXISTING" -ne 1 ]]; then
    log "removing previous output: $OUT_DIR"
    rm -rf -- "$OUT_DIR"
  fi
  mkdir -p "$OUT_DIR"

  log "running: 3dsrecomp port (generation + parallel iOS clang compile)"
  log "  this can take a long time for large games; follow: tail -f \"$LOG_FILE\""
  port_status=0
  ( cd "$ROOT" && CC="$CC_STRING" AR=ar "$RECOMP_BIN" port "$ROM_ABS" "$OUT_DIR" --name "$NAME" ) \
    >>"$LOG_FILE" 2>&1 || port_status=$?
  if [[ "$port_status" -ne 0 ]]; then
    if [[ "$AUTO_SERIAL" -eq 1 ]] && compgen -G "${CODE_DIR}/*.c" >/dev/null; then
      warn "3dsrecomp port failed (status ${port_status}); --auto-serial: compiling the
       generated C serially instead (8 GB VM memory fallback, scripts/AOT_BUILD.md §3.2)."
      serial_compile
    else
      printf '\n--- 3dsrecomp port failed: last 100 lines of %s ---\n' "$LOG_FILE" >&2
      tail -n 100 "$LOG_FILE" >&2
      die "3dsrecomp port failed (status ${port_status}); full log: $LOG_FILE
       On a low-memory macOS VM retry with --auto-serial (or --serial-compile)."
    fi
  fi
fi

