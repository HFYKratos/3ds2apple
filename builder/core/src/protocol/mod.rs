//! Protocol version, wire limits, validation rules and the shared protocol
//! error type.
//!
//! The validation rules here are the single source of truth for both sides: the
//! Agent rejects a request that fails them, and the Builder refuses to send one.

pub mod codes;
pub mod frames;
pub mod model;

pub use codes::ErrorCode;
pub use frames::*;
pub use model::*;

/// The protocol string this build implements.
pub const PROTOCOL: &str = "3ds2apple-builder/1";
/// Protocol major version.
pub const PROTOCOL_MAJOR: u32 = 1;
/// Maximum size of one control frame (PROTOCOL.md §3.3).
pub const MAX_FRAME_BYTES: usize = 1024 * 1024;
/// Maximum size of one log line before it is split into parts.
pub const MAX_LOG_LINE_BYTES: usize = 32 * 1024;
/// Suggested upload chunk (`chunk_hint` in `job.created`).
pub const DEFAULT_CHUNK_HINT: u64 = 8 * 1024 * 1024;
/// Upload progress is reported to the client every N bytes.
pub const UPLOAD_PROGRESS_EVERY: u64 = 4 * 1024 * 1024;

/// Extract the major version from a protocol string.
pub fn protocol_major(value: &str) -> Option<u32> {
    value
        .strip_prefix("3ds2apple-builder/")?
        .parse::<u32>()
        .ok()
}

/// Whether a peer's protocol string is compatible with this build.
pub fn protocol_compatible(value: &str) -> bool {
    protocol_major(value) == Some(PROTOCOL_MAJOR)
}

/// Case-insensitive hex length check used for hash fields.
pub fn is_hex(value: &str, length: usize) -> bool {
    value.len() == length && value.bytes().all(|b| b.is_ascii_hexdigit())
}

/// Validate and normalise a SHA256 string to lowercase hex.
pub fn normalize_sha256(value: &str) -> Option<String> {
    if is_hex(value, 64) {
        Some(value.to_ascii_lowercase())
    } else {
        None
    }
}

/// `game.name` rule from PROTOCOL.md §6.2. This also matches the build scripts'
/// name rule, so a valid value is safe as a path component and an argument.
pub fn valid_game_name(value: &str) -> bool {
    let bytes = value.as_bytes();
    if bytes.is_empty() || bytes.len() > 64 {
        return false;
    }
    if !bytes[0].is_ascii_alphanumeric() {
        return false;
    }
    bytes
        .iter()
        .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'_' | b'-'))
}

/// Validate `game.name`, returning a human-readable reason on failure.
pub fn validate_game_name(value: &str) -> Result<(), String> {
    if valid_game_name(value) {
        Ok(())
    } else {
        Err(format!(
            "game name must match [A-Za-z0-9][A-Za-z0-9._-]{{0,63}}, got {value:?}"
        ))
    }
}

/// `game.display_name` rule: 1–48 printable characters, no path separators and
/// no control characters. The name is shown on the home screen.
pub fn validate_display_name(value: &str) -> Result<(), String> {
    let count = value.chars().count();
    if count == 0 || count > 48 {
        return Err("display name must be 1-48 characters".to_string());
    }
    if value.chars().any(char::is_control) {
        return Err("display name must not contain control characters".to_string());
    }
    if value.contains('/') || value.contains('\\') {
        return Err("display name must not contain path separators".to_string());
    }
    if value == "." || value == ".." {
        return Err("display name must not be a path component".to_string());
    }
    Ok(())
}

/// Validate an optional reverse-DNS bundle identifier.
pub fn validate_bundle_id(value: &str) -> Result<(), String> {
    if value.len() > 155 {
        return Err("bundle id is longer than 155 characters".to_string());
    }
    let segments: Vec<&str> = value.split('.').collect();
    if segments.len() < 2 {
        return Err("bundle id needs at least two dot-separated segments".to_string());
    }
    for segment in segments {
        let bytes = segment.as_bytes();
        if bytes.is_empty() || bytes.len() > 63 {
            return Err("each bundle id segment must be 1-63 characters".to_string());
        }
        if !bytes[0].is_ascii_alphanumeric() || !bytes[bytes.len() - 1].is_ascii_alphanumeric() {
            return Err("bundle id segments must start and end with a letter or digit".to_string());
        }
        if !bytes
            .iter()
            .all(|b| b.is_ascii_alphanumeric() || *b == b'-')
        {
            return Err("bundle id allows only letters, digits, '-' and '.'".to_string());
        }
    }
    Ok(())
}

/// A 3DS title id is exactly 16 hex digits.
pub fn valid_title_id(value: &str) -> bool {
    is_hex(value, 16)
}

/// Job ids are generated by the Agent so they never carry client-controlled
/// path components; the shape is checked again on every read.
pub fn valid_job_id(value: &str) -> bool {
    const CROCKFORD: &str = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";
    let Some(rest) = value.strip_prefix("job_") else {
        return false;
    };
    rest.len() == 26 && rest.bytes().all(|b| CROCKFORD.as_bytes().contains(&b))
}

/// Request ids are client-chosen idempotency keys.
pub fn valid_request_id(value: &str) -> bool {
    let bytes = value.as_bytes();
    !bytes.is_empty()
        && bytes.len() <= 128
        && bytes
            .iter()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'_' | b':' | b'-'))
}

/// `artifact.json` file names are always relative single components.
pub fn valid_file_name(value: &str) -> bool {
    if value.is_empty() || value.len() > 255 {
        return false;
    }
    if value == "." || value == ".." {
        return false;
    }
    !value
        .chars()
        .any(|c| c.is_control() || c == '/' || c == '\\' || c == ':')
}

/// Map a ROM file name to a build slug within the scripts' name rule.
///
/// The mapping is intentionally simple and lossy: non-ASCII names produce
/// `game`; the UI lets the user edit the result before building.
pub fn slugify_game_name(file_stem: &str) -> String {
    let mut out = String::new();
    let mut last_dash = false;
    for ch in file_stem.chars() {
        let mapped = ch.to_ascii_lowercase();
        if mapped.is_ascii_alphanumeric() || mapped == '.' || mapped == '_' {
            out.push(mapped);
            last_dash = false;
        } else if mapped == '-' {
            if !last_dash && !out.is_empty() {
                out.push('-');
                last_dash = true;
            }
        } else if !last_dash && !out.is_empty() {
            out.push('-');
            last_dash = true;
        }
    }
    while out.ends_with('-') || out.ends_with('.') {
        out.pop();
    }
    while out.starts_with(|c: char| !c.is_ascii_alphanumeric()) {
        out.remove(0);
    }
    if out.len() > 64 {
        out.truncate(64);
        while out.ends_with('-') || out.ends_with('.') {
            out.pop();
        }
    }
    if out.is_empty() {
        out.push_str("game");
    }
    out
}

/// Shared decode/encode error for the protocol layer.
#[derive(Debug, thiserror::Error)]
pub enum ProtocolError {
    #[error("i/o error: {0}")]
    Io(#[from] std::io::Error),
    #[error("invalid JSON: {0}")]
    Json(#[from] serde_json::Error),
    #[error("frame too large: {bytes} bytes (limit {limit})")]
    FrameTooLarge { bytes: usize, limit: usize },
    #[error("frame is not a JSON object")]
    NotAnObject,
    #[error("unsupported protocol {got:?}; this build speaks {expected}")]
    UnsupportedProtocol { got: String, expected: &'static str },
    #[error("expected frame type {expected:?}, got {got:?}")]
    MismatchedFrameType { expected: &'static str, got: String },
    #[error("invalid field {field}: {message}")]
    InvalidField {
        field: &'static str,
        message: String,
    },
}

impl ProtocolError {
    pub fn invalid_field(field: &'static str, message: impl Into<String>) -> Self {
        ProtocolError::InvalidField {
            field,
            message: message.into(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn protocol_string_and_major() {
        assert_eq!(protocol_major(PROTOCOL), Some(1));
        assert!(protocol_compatible("3ds2apple-builder/1"));
        assert!(!protocol_compatible("3ds2apple-builder/2"));
        assert!(!protocol_compatible("3ds2apple-builder/x"));
        assert_eq!(protocol_major("other/1"), None);
    }

    #[test]
    fn game_name_rule() {
        for ok in ["pokemon-y", "Pokemon_Y", "a", "Game.v1", "x1234567890"] {
            assert!(valid_game_name(ok), "{ok} should be valid");
        }
        for bad in [
            "",
            "-x",
            ".hidden",
            "with space",
            "sla/sh",
            "..",
            "x".repeat(65).as_str(),
            "café",
        ] {
            assert!(!valid_game_name(bad), "{bad:?} should be invalid");
        }
        assert!(validate_game_name("pokemon-y").is_ok());
        assert!(validate_game_name("-bad").is_err());
    }

    #[test]
    fn display_name_rule() {
        assert!(validate_display_name("Pokemon Y").is_ok());
        assert!(validate_display_name("宝可梦 Y").is_ok());
        assert!(validate_display_name("").is_err());
        assert!(validate_display_name("x".repeat(49).as_str()).is_err());
        assert!(validate_display_name("a/b").is_err());
        assert!(validate_display_name("a\nb").is_err());
        assert!(validate_display_name("..").is_err());
    }

    #[test]
    fn bundle_id_rule() {
        assert!(validate_bundle_id("com.kratos.3ds2apple.pokemon-y").is_ok());
        assert!(validate_bundle_id("com.example").is_ok());
        assert!(validate_bundle_id("nodots").is_err());
        assert!(validate_bundle_id("com..example").is_err());
        assert!(validate_bundle_id("-bad.example").is_err());
        assert!(validate_bundle_id("com.exa_mple").is_err());
    }

    #[test]
    fn hash_and_id_rules() {
        let ok = "a".repeat(64);
        assert_eq!(normalize_sha256(&ok), Some(ok.clone()));
        assert_eq!(normalize_sha256(&"A".repeat(64)), Some(ok));
        assert_eq!(normalize_sha256("abc"), None);
        assert_eq!(normalize_sha256(&"z".repeat(64)), None);
        assert!(valid_title_id("0004000000055E00"));
        assert!(!valid_title_id("0004000000055E0"));
        assert!(valid_job_id("job_01J8Z3K4T9ABCDEFGHJKMNPQRS"));
        assert!(!valid_job_id("job_../etc"));
        assert!(!valid_job_id("01J8Z3K4T9ABCDEFGHJKMNPQRS"));
        assert!(valid_request_id("6f1c2b1e-3d1a-4b8e-9f2c-1e2d3c4b5a69"));
        assert!(!valid_request_id(""));
        assert!(!valid_request_id("has space"));
        assert!(valid_file_name("pokemon-y-AOT.ipa"));
        assert!(!valid_file_name("a/b"));
        assert!(!valid_file_name(".."));
    }

    #[test]
    fn slugify_covers_common_rom_names() {
        assert_eq!(slugify_game_name("Pokemon Y"), "pokemon-y");
        assert_eq!(slugify_game_name("Pokemon_Y"), "pokemon_y");
        assert_eq!(slugify_game_name("Pokemon.Y"), "pokemon.y");
        assert_eq!(slugify_game_name("   "), "game");
        assert_eq!(slugify_game_name("--x--"), "x");
        assert_eq!(slugify_game_name("宝可梦"), "game");
        assert!(valid_game_name(&slugify_game_name(
            "Some Really Long Game Name (Rev 1).cci"
        )));
        assert_eq!(slugify_game_name("x".repeat(100).as_str()).len(), 64);
    }
}
